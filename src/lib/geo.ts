export function statesForCountry(country: string): string[] | null {
  if (!country || country === OTHER_COUNTRY) return null;
  const list = STATES_BY_COUNTRY[country];
  return list?.length ? list : null;
}

/** Resolved country name for display/submit (typed name when Other). */
export function resolvedCountry(country: string, countryOther: string): string {
  if (country === OTHER_COUNTRY) return countryOther.trim();
  return country;
}
